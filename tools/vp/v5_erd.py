"""Phase 4: the data model (tables) is generated from the class diagram with ORM, never drawn by hand.

    python tools/vp/v5_erd.py      clears the data model DM01, runs syncClassesToErd on ORM01, applies the key decisions,
                                   writes design/create_tables.sql with generateSql and logs every call
"""
import os
import re

import vp
from v5_merge import arrange

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DM = "ORM01 Class Diagram with Multiplicity and Labels (ORM)"
ERD = "DM01 Data Model (generated by syncClassesToErd)"
LOG = []


def call(tool, **args):
    out = vp.call(tool, quiet=True, **args)
    shown = ", ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in args.values())
    LOG.append(f"$ {tool}({shown})\n{out.strip()}\n")
    return out


def clear():
    """Remove the tables of an earlier run (foreign keys first), so the data model comes from this sync only."""
    r = vp.call("getDiagramElements", quiet=True, diagramName=ERD)
    for p, c in re.findall(r"ForeignKey(?: '[^']*')?: (\S+) -> (\S+)", r):
        vp.call("removeForeignKey", quiet=True, diagramName=ERD, parentTable=p, childTable=c)
    for t in re.findall(r"Table: (\S+)", r):
        vp.call("removeTable", quiet=True, diagramName=ERD, tableName=t)


DECISIONS = [
    ("renameElement", dict(elementName="Order", newName="Orders")),
    ("renameColumn", dict(tableName="Address", columnName="user_id", newName="customer_id")),
    ("renameColumn", dict(tableName="Cart", columnName="user_id", newName="customer_id")),
    ("renameColumn", dict(tableName="Orders", columnName="user_id", newName="customer_id")),
    ("renameColumn", dict(tableName="Review", columnName="user_id", newName="customer_id")),
    ("renameColumn", dict(tableName="Orders", columnName="code", newName="promo_code")),
    ("setPrimaryKey", dict(tableName="Address", columnNames="customer_id")),
    ("setPrimaryKey", dict(tableName="StockLevel", columnNames="product_id")),
    ("setPrimaryKey", dict(tableName="CartItem", columnNames="cart_id,product_id")),
    ("setPrimaryKey", dict(tableName="OrderItem", columnNames="order_id,product_id")),
    ("setPrimaryKey", dict(tableName="Milestone", columnNames="shipment_id,seq")),
]

if __name__ == "__main__":
    clear()
    LOG.append("==== 1. Class diagram with ORM to data model " + "=" * 57)
    call("syncClassesToErd", classDiagramName=DM, erdName=ERD,
         primaryKeys="Promotion=code; InventoryEvent=event_id; ReplenishmentRequest=request_id")
    LOG.append("==== 2. Decisions applied to the generated data model " + "=" * 45)
    for tool, args in DECISIONS:
        call(tool, diagramName=ERD, **args)
    for t in ("Address", "StockLevel", "CartItem", "OrderItem", "Milestone"):
        call("removeColumn", diagramName=ERD, tableName=t, columnName="ID")
    arrange(ERD, rename={"Orders": "Order"})                 # the grid of ORM01, so table and class sit alike
    LOG.append("==== 3. Data model to SQL " + "=" * 73)
    call("generateSql", diagramName=ERD, database="SQLite", statements="create",
         outputFile=os.path.join(ROOT, "design", "create_tables.sql"))
    r = vp.call("getDiagramElements", quiet=True, diagramName=ERD)
    LOG.append(f"Result: {len(re.findall('Table: ', r))} tables, {len(re.findall('ForeignKey', r))} foreign keys")
    head = ("Calls of the Visual Paradigm MCP plugin 1.33.0 (Visual Paradigm Enterprise 18.1, ABC_Online_Shop_4_Design.vpp) and the\n"
            "result strings they returned, in order (tools/vp/v5_erd.py; the code generation, section 4, is in v5_design_build.py).\n\n")
    old = open(os.path.join(ROOT, "design", "v5_tool_log.txt"), encoding="utf-8").read()
    code = old[old.index("==== 4. Design class diagrams to code"):] if "==== 4." in old else ""
    open(os.path.join(ROOT, "design", "v5_tool_log.txt"), "w", encoding="utf-8").write(head + "\n".join(LOG) + "\n" + code)
    vp.call("exportDiagramImage", quiet=True, diagramName=ERD, filePath=vp.PNG + ERD + ".png")
    vp.call("saveProject", quiet=True)
    print("\n".join(LOG[-3:]))
