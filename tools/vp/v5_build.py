"""Draws the V5 class models in the open Visual Paradigm project through the MCP plugin (tools/vp/vp.py).

    python tools/vp/v5_build.py analysis     CL01, CL02  (package Analysis)
    python tools/vp/v5_build.py datamodel    DM01, DM02  (package Data Model, <<ORM Persistable>>)
    python tools/vp/v5_build.py erd          syncClassesToErd -> ERD01, then the documented key and name edits
Every result string is printed when it reports a problem; the layout is the plugin's (orthogonal, no overlap).
"""
import sys

import vp
from v5_spec import ASSOCIATIONS, CLASSES, FIGURES

ANALYSIS = {"core": "CL01 Analysis Classes - Customers Catalogue and Orders",
            "after": "CL02 Analysis Classes - Order History Delivery Stock and Reviews"}
DATAMODEL = {"core": "DM01 Data Model Classes - Customers Catalogue and Orders",
             "after": "DM02 Data Model Classes - Order History Delivery Stock and Reviews"}
ERD = "ERD01 Data Model Generated by syncClassesToErd"


def draw(diagrams, package, typed):
    """typed=False: analysis (no identifier, no type); typed=True: data model (types, identifiers, roles)."""
    made = set()
    for fig, names in FIGURES.items():
        d = diagrams[fig]
        vp.call("createClassDiagram", quiet=True, diagramName=d)
        for name in names:                                   # parents first, so generalizations can be drawn
            vp.call("addClass", quiet=True, diagramName=d, className=name, modelPackage=package)
            if name in made:
                continue
            made.add(name)
            parent, attrs, ops = CLASSES[name]
            for attr, typ, key in attrs:
                if key and not typed:
                    continue
                vp.call("addAttribute", quiet=True, className=name, attributeName=attr,
                        attributeType=typ if typed else "", visibility="public", diagramName=d)
            for op, params, ret in ops:
                vp.call("addOperation", quiet=True, className=name, operationName=op, returnType=ret,
                        params=params, visibility="public", diagramName=d)
        for name in names:
            parent = CLASSES[name][0]
            if parent and parent in names:
                vp.call("addGeneralization", quiet=True, diagramName=d, fromClass=name, toClass=parent)
    drawn = set()
    for fig, names in FIGURES.items():
        d = diagrams[fig]
        for a, b, ma, mb, label, kind, ra, rb in ASSOCIATIONS:
            if a in names and b in names and (a, b) not in drawn:
                drawn.add((a, b))
                if kind == "comp":
                    vp.call("addComposition", quiet=True, diagramName=d, fromClass=a, toClass=b,
                            fromMultiplicity=ma, toMultiplicity=mb)
                    vp.call("setAssociationProperties", quiet=True, diagramName=d, fromClass=a, toClass=b, name=label)
                else:
                    vp.call("addAssociation", quiet=True, diagramName=d, fromClass=a, toClass=b,
                            fromMultiplicity=ma, toMultiplicity=mb, name=label)
                if typed:
                    vp.call("setAssociationProperties", quiet=True, diagramName=d, fromClass=a, toClass=b,
                            fromRole=ra, toRole=rb)
        if typed:
            vp.call("addStereotypeToClasses", quiet=True, diagramName=d, classNames="*",
                    stereotype="ORM Persistable", robustnessIcon="false")
        vp.call("autoLayoutDiagram", quiet=True, diagramName=d)
        vp.call("layoutConnectorLabels", quiet=True, diagramName=d)
        print(vp.call("getElementCounts", quiet=True, diagramName=d))
        vp.call("exportDiagramImage", quiet=True, diagramName=d, filePath=vp.PNG + d + ".png")
    missing = [x for x in ASSOCIATIONS if (x[0], x[1]) not in drawn]
    print("associations drawn", len(drawn), "missing", missing)


if __name__ == "__main__":
    what = sys.argv[1]
    if what == "analysis":
        draw(ANALYSIS, "Analysis", typed=False)
    elif what == "datamodel":
        draw(DATAMODEL, "Data Model", typed=True)
    vp.call("saveProject", quiet=True)
