def shift(blocks):
    """V4 text numbered design as Chapter 4 and implementation as Chapter 5; V5 has the data model in 4, design in 5
    and implementation in 6."""
    def fix(t):
        t = t.replace("Chapter 5", "Chapter @@6").replace("Chapter 4", "Chapter 5").replace("Chapter @@6", "Chapter 6")
        t = t.replace("Chapters 4 and 5", "Chapters 5 and 6").replace("the 40 tests", "the 45 tests")
        return t.replace("(Section 4.4.4)", "(Section 5.1.2)")
    out = []
    for b in blocks:
        if b[0] in ("p", "eq"):
            b = (b[0], fix(b[1])) + tuple(b[2:])
        elif b[0] == "bullets":
            b = ("bullets", [fix(x) for x in b[1]])
        elif b[0] == "table":
            b = (b[0], fix(b[1]), b[2], [[fix(str(c)) for c in r] for r in b[3]]) + tuple(b[4:])
        out.append(b)
    return out

