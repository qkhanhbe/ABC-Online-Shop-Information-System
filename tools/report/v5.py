def path(code):
    return next(os.path.join(D, f) for f in sorted(os.listdir(D)) if f.startswith(code + " "))


def fig(code, caption, width=160):
    p = path(code)
    return ("fig", p, caption + f" - VP diagram \"{os.path.basename(p)[:-4]}\"", width)


def figl(code, caption):
    p = path(code)
    return ("figl", p, caption + f" - VP diagram \"{os.path.basename(p)[:-4]}\"")


def figm(code, caption, marks, width=160, landscape=True):
    """A diagram with red numbered callouts; marks = [(target, note)]."""
    p = path(code)
    img = annotate(code, [(i, t) for i, (t, _) in enumerate(marks, 1)])
    return ("figm", img, caption + f" - VP diagram \"{os.path.basename(p)[:-4]}\"", width, [n for _, n in marks],
            landscape)


