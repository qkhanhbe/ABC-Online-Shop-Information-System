"""DAO layer: interfaces (design Step 3).

Services depend only on these abstract classes; the SQLite implementations in sqlite_dao.py
are the only classes that know how data is stored. A missing record returns None or [],
which is an expected outcome, not an error.
"""
from abc import ABC, abstractmethod


class CustomerDAO(ABC):
    @abstractmethod
    def get_user(self, user_id): ...
    @abstractmethod
    def find_by_email(self, email): ...
    @abstractmethod
    def save_user(self, user): ...
    @abstractmethod
    def list_customers(self): ...


class ProductDAO(ABC):
    @abstractmethod
    def get_product(self, product_id): ...
    @abstractmethod
    def list_products(self, category_id=None, active_only=True): ...
    @abstractmethod
    def save_product(self, product): ...
    @abstractmethod
    def list_categories(self): ...
    @abstractmethod
    def save_category(self, category): ...


class InventoryDAO(ABC):
    @abstractmethod
    def get_stock(self, product_id): ...
    @abstractmethod
    def save_stock(self, stock): ...
    @abstractmethod
    def find_event(self, product_id, kind, reference): ...
    @abstractmethod
    def add_event(self, event): ...
    @abstractmethod
    def events_for(self, product_id, limit=10): ...
    @abstractmethod
    def add_replenishment(self, request_id, product_id, quantity, at): ...
    @abstractmethod
    def open_replenishments(self): ...


class CartDAO(ABC):
    @abstractmethod
    def get_cart(self, customer_id): ...
    @abstractmethod
    def update_cart(self, cart): ...


class PromotionDAO(ABC):
    @abstractmethod
    def get_promotion(self, code): ...
    @abstractmethod
    def save_promotion(self, promotion): ...
    @abstractmethod
    def list_promotions(self): ...


class OrderDAO(ABC):
    @abstractmethod
    def get_order(self, order_id): ...
    @abstractmethod
    def find_by_idempotency_key(self, key): ...
    @abstractmethod
    def find_by_customer(self, customer_id): ...
    @abstractmethod
    def find_by_status(self, *statuses): ...
    @abstractmethod
    def save_order(self, order): ...
    @abstractmethod
    def list_orders(self): ...


class PaymentDAO(ABC):
    @abstractmethod
    def get_by_attempt(self, attempt_ref): ...
    @abstractmethod
    def for_order(self, order_id): ...
    @abstractmethod
    def save_payment(self, payment): ...


class ShipmentDAO(ABC):
    @abstractmethod
    def get_by_order(self, order_id): ...
    @abstractmethod
    def get_by_carrier_ref(self, carrier_ref): ...
    @abstractmethod
    def save_shipment(self, shipment): ...


class ReviewDAO(ABC):
    @abstractmethod
    def for_product(self, product_id, status="published"): ...
    @abstractmethod
    def exists(self, customer_id, product_id, order_id): ...
    @abstractmethod
    def save_review(self, review): ...
    @abstractmethod
    def list_reviews(self, status=None): ...


class AuditDAO(ABC):
    @abstractmethod
    def record(self, actor, action, entity, entity_id, detail=""): ...
    @abstractmethod
    def recent(self, limit=20): ...
